function seed() {
    console.log('1. Cleaning previous TGAT3 records...');

    // Get old TGAT3 questions
    const oldQRows = db.prepare("SELECT id FROM questions WHERE subject_id = 'tgat3'").all();
    const oldQIds = oldQRows.map(r => r.id);
    console.log(`Found ${oldQIds.length} existing questions for TGAT3 to be replaced.`);

    const delOption = db.prepare("DELETE FROM question_options WHERE question_id = ?");
    const delMistake = db.prepare("DELETE FROM mistake_notebook WHERE question_id = ?");
    const delMastered = db.prepare("DELETE FROM user_mastered_questions WHERE question_id = ?");
    const delAnswer = db.prepare("DELETE FROM user_answers WHERE question_id = ?");
    const delQ = db.prepare("DELETE FROM questions WHERE id = ?");

    const deleteTx = db.transaction(() => {
        for (const qid of oldQIds) {
            delOption.run(qid);
            delMistake.run(qid);
            delMastered.run(qid);
            delAnswer.run(qid);
            delQ.run(qid);
        }
    });
    deleteTx();
    console.log('✅ Cleaned old TGAT3 questions and related child records.');

    // 2. Upsert Blueprints for TGAT3
    console.log('2. Updating blueprints for TGAT3 (4 domains)...');
    db.prepare("DELETE FROM blueprints WHERE subject_id = 'tgat3'").run();

    const insertBp = db.prepare(`
        INSERT INTO blueprints (id, subject_id, domain_name, subtopic_name, description, target_questions, score_weight, order_index)
        VALUES (@id, @subject_id, @domain_name, @subtopic_name, @description, @target_questions, @score_weight, @order_index)
    `);

    const bpTx = db.transaction(() => {
        for (const bp of tgat3Blueprints) {
            insertBp.run(bp);
        }
    });
    bpTx();
    console.log(`✅ Seeded ${tgat3Blueprints.length} official TGAT3 blueprints.`);

    // 3. Insert questions and options
    console.log('3. Inserting 60 authentic TGAT3 questions with 240 options...');
    const insertQ = db.prepare(`
        INSERT INTO questions (id, subject_id, blueprint_id, stimulus, question_text, image_url, difficulty, explanation, trap_analysis, is_custom)
        VALUES (@id, @subject_id, @blueprint_id, @stimulus, @question_text, @image_url, @difficulty, @explanation, @trap_analysis, 0)
    `);

    const insertOpt = db.prepare(`
        INSERT INTO question_options (id, question_id, label, content, is_correct, order_index)
        VALUES (@id, @question_id, @label, @content, @is_correct, @order_index)
    `);

    const insertTx = db.transaction(() => {
        for (const q of tgat3Questions) {
            insertQ.run({
                id: q.id,
                subject_id: q.subject_id,
                blueprint_id: q.blueprint_id,
                stimulus: q.stimulus || null,
                question_text: q.question_text,
                image_url: q.image_url || null,
                difficulty: q.difficulty || 'medium',
                explanation: q.explanation || '',
                trap_analysis: q.trap_analysis || ''
            });

            q.options.forEach((opt, idx) => {
                insertOpt.run({
                    id: `${q.id}_opt_${idx + 1}`,
                    question_id: q.id,
                    label: opt.label,
                    content: opt.content,
                    is_correct: opt.is_correct,
                    order_index: idx
                });
            });
        }
    });
    insertTx();
    console.log(`✅ Successfully seeded all ${tgat3Questions.length} official TGAT3 questions with options!`);

    // 4. Update subjects metadata for TGAT3 (60 questions, 100 score, 60 mins)
    console.log('4. Updating subjects table metadata for TGAT3...');
    db.prepare(`
        UPDATE subjects 
        SET total_questions = 60, total_score = 100, duration_minutes = 60
        WHERE id = 'tgat3'
    `).run();

    console.log('🎉 TGAT3 Official Blueprint Calibration Completed Successfully!');
}

if (require.main === module) {
    seed();
}

module.exports = { seed, tgat3Questions, tgat3Blueprints };
