function create5Options(correctContent, wrongContents, correctIndex = 0) {
    const opts = [];
    let wrongIdx = 0;
    for (let i = 0; i < 5; i++) {
        if (i === correctIndex) {
            opts.push({
                label: String(i + 1),
                content: String(correctContent),
                is_correct: 1
            });
        } else {
            opts.push({
                label: String(i + 1),
                content: String(wrongContents[wrongIdx++] || '0'),
                is_correct: 0
            });
        }
    }
    return opts;
}

